#!/usr/bin/env python3
"""Extract the barcode captures logged on the car into a C table for the
S3-U05 replay test.

    python3 testing/subsystem3/extract_captures.py > testing/subsystem3/recorded_captures.h

Only rejected captures print their runs on the console ("s3 bar: capture
rejected, runs=N" followed by "s3 bar:  runs i..: ..." lines), plus the two
decoded stray-mark passes already replayed by test_scan_recorded(). A
capture whose run lines are interleaved with other console output, or that
has fewer than 20 runs (too short for any decode path), is left out. Each
capture carries the letters printed on the course in that session, so the
test can tell a wrong letter from a right one.
"""
import glob
import re
import sys

# Letters printed on the course in each logging session.
SESSION_LETTERS = {
    "2026-11-17": "F",
    "2026-11-24": "AFQ",
}

HEADER = re.compile(r"s3 bar: capture rejected, runs=(\d+)")
RUNS = re.compile(r"s3 bar:\s+runs \d+\.\.:\s*(.*)$")


def captures(path):
    """Yield (line number, runs) for every cleanly logged capture."""
    lines = open(path, errors="replace").read().splitlines()
    for index, line in enumerate(lines):
        match = HEADER.search(line)
        if not match:
            continue
        count = int(match.group(1))
        runs = []
        clean = True
        for follow in lines[index + 1:index + 12]:
            if len(runs) >= count:
                break
            run_match = RUNS.search(follow)
            if run_match:
                tokens = run_match.group(1).split()
                clean = clean and all(token.isdigit() for token in tokens)
                runs += [int(token) for token in tokens if token.isdigit()]
        if clean and len(runs) == count and count >= 20:
            yield index + 1, runs


def main():
    rows = []
    for path in sorted(glob.glob("testing/subsystem3/logs/*.txt")):
        name = path.rsplit("/", 1)[-1]
        letters = SESSION_LETTERS.get(name[:10])
        if letters is None:
            continue
        for line, runs in captures(path):
            rows.append((name, line, letters, runs))

    out = sys.stdout
    out.write("/* Generated by testing/subsystem3/extract_captures.py from the\n"
              " * console logs in testing/subsystem3/logs/. Do not edit. */\n")
    out.write("#define RECORDED_CAPTURE_COUNT %dU\n\n" % len(rows))
    out.write("static recorded_capture_t const g_recorded[RECORDED_CAPTURE_COUNT] =\n{\n")
    for name, line, letters, runs in rows:
        body = ", ".join("%dU" % run for run in runs)
        out.write('    {"%s:%d", "%s", %dU,\n     {%s}},\n'
                  % (name, line, letters, len(runs), body))
    out.write("};\n")


if __name__ == "__main__":
    main()
